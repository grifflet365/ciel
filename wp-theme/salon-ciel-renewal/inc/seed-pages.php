/* ---------- 実行(1回だけ) ---------- */
add_action( 'init', function () {
	if ( (int) get_option( 'ciel_seed_ver', 0 ) >= 2 ) {
		return;
	}
	if ( ! get_option( 'ciel_seeded' ) ) {
		return; // 第1弾が先(テーマ有効化時に走る)
	}
	foreach ( ciel_seed_pages_data() as $slug => $d ) {
		if ( get_page_by_path( $slug ) ) {
			continue;
		}
		wp_insert_post( array(
			'post_title'   => $d[0],
			'post_name'    => $slug,
			'post_content' => $d[2],
			'post_status'  => 'publish',
			'post_type'    => 'page',
			'menu_order'   => $d[1],
		) );
	}
	update_option( 'ciel_seed_ver', 2 );
	flush_rewrite_rules();
}, 30 );

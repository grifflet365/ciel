/* ---------- ブロック(エディタ用HTML)を作る小さな道具 ---------- */
function ciel_b_h( $text, $level = 2 ) {
	return "<!-- wp:heading {\"level\":{$level}} -->\n<h{$level} class=\"wp-block-heading\">{$text}</h{$level}>\n<!-- /wp:heading -->\n\n";
}
function ciel_b_p( $text, $class = '' ) {
	if ( $class ) {
		return "<!-- wp:paragraph {\"className\":\"{$class}\"} -->\n<p class=\"{$class}\">{$text}</p>\n<!-- /wp:paragraph -->\n\n";
	}
	return "<!-- wp:paragraph -->\n<p>{$text}</p>\n<!-- /wp:paragraph -->\n\n";
}
function ciel_b_ul( $items ) {
	$li = '';
	foreach ( $items as $i ) {
		$li .= '<li>' . $i . '</li>';
	}
	return "<!-- wp:list -->\n<ul class=\"wp-block-list\">{$li}</ul>\n<!-- /wp:list -->\n\n";
}
function ciel_b_table( $rows, $head = array() ) {
	$h = '';
	if ( $head ) {
		$h = '<thead><tr>';
		foreach ( $head as $c ) {
			$h .= '<th>' . $c . '</th>';
		}
		$h .= '</tr></thead>';
	}
	$b = '<tbody>';
	foreach ( $rows as $r ) {
		$b .= '<tr>';
		foreach ( $r as $c ) {
			$b .= '<td>' . $c . '</td>';
		}
		$b .= '</tr>';
	}
	$b .= '</tbody>';
	return "<!-- wp:table {\"className\":\"ciel-table\"} -->\n<figure class=\"wp-block-table ciel-table\"><table>{$h}{$b}</table></figure>\n<!-- /wp:table -->\n\n";
}

